import { logger } from "@/lib/logger";
import { SupplierNotActiveError } from "@/modules/procurement";

import type {
  IRestockApprovalRepository,
  RestockDecidedRequest,
  RestockRequestForDecision,
} from "../domain/ports/IRestockApprovalRepository";
import {
  RESTOCK_APPROVAL_MESSAGES,
  resolveRestockApprovalDecision,
  type RestockApprovalBarangDecision,
  type RestockApprovalJasaDecision,
  type RestockApprovalPlan,
  type RestockBarangLinePlan,
  type RestockJasaLinePlan,
} from "../domain/restock-approval-decision";
import {
  RESTOCK_MESSAGES,
  restockAlreadyDecidedMessage,
} from "./restock-messages";

/** Penjelasan untuk penyetuju bila daftar belanja tidak bisa dibuat otomatis setelah disetujui. */
const PO_SUPPLIER_INACTIVE_MESSAGE =
  "Pengajuan sudah disetujui, tapi daftar belanjanya belum bisa dibuat karena toko untuk barang ini sedang tidak aktif. Hubungi admin.";
const PO_NOT_GENERATED_MESSAGE =
  "Pengajuan sudah disetujui, tapi daftar belanjanya belum bisa dibuat. Hubungi admin.";

const LIFECYCLE_DECISION_WORDS = {
  APPROVE: "disetujui",
  REJECT: "ditolak",
} as const;

const UNDECIDED_STATUS = "DRAFT";

/** Pembuat PO otomatis; dipenuhi oleh `ProcurementService` lewat factory. */
export interface RestockPurchaseOrderGenerator {
  generatePOFromPRs(
    purchaseRequestIds: string[],
    actorId: string,
  ): Promise<Array<{ id: string; poNumber: string }>>;
}

interface RestockLifecycleCommandBase {
  id: string;
  tenantId: string;
  actorId: string;
}

/** Tolak seluruh pengajuan dengan alasan. */
export interface RestockRejectCommand extends RestockLifecycleCommandBase {
  action: "REJECT";
  catatan: string;
}

/** Setujui pengajuan dengan keputusan per baris barang dan jasa. */
export interface RestockApproveCommand extends RestockLifecycleCommandBase {
  action: "APPROVE";
  catatan?: string;
  items: RestockApprovalBarangDecision[];
  jasaItems: RestockApprovalJasaDecision[];
}

export type RestockLifecycleCommand =
  | RestockRejectCommand
  | RestockApproveCommand;

/** `INVALID` → 400, `NOT_FOUND` → 404, `CONFLICT` → 409. */
export type RestockLifecycleErrorCode = "INVALID" | "NOT_FOUND" | "CONFLICT";

/** Isi respons setelah disetujui: pengajuan + hasil PO otomatis. */
export type RestockApprovedResponse = RestockDecidedRequest & {
  _autoGeneratedPO: { id: string; poNumber: string } | null;
  _poError: string | null;
};

export type RestockLifecycleResult =
  | {
      success: true;
      data: RestockDecidedRequest | RestockApprovedResponse;
    }
  | { success: false; code: RestockLifecycleErrorCode; error: string };

interface GeneratedPurchaseOrderOutcome {
  generatedPO: { id: string; poNumber: string } | null;
  poError: string | null;
}

/**
 * Keputusan setuju/tolak atas pengajuan restock. Aturan per baris ada di
 * `resolveRestockApprovalDecision`; service ini mengatur urutan muat →
 * putuskan → simpan → buat PO (best-effort) → catat aktivitas.
 */
export class RestockRequestLifecycleService {
  constructor(
    private readonly repository: IRestockApprovalRepository,
    private readonly purchaseOrderGenerator: RestockPurchaseOrderGenerator,
  ) {}

  /** Jalankan keputusan penyetuju atas pengajuan restock. */
  async patchRestockRequestLifecycle(
    command: RestockLifecycleCommand,
  ): Promise<RestockLifecycleResult> {
    const request = await this.repository.findRequestForDecision(
      command.id,
      command.tenantId,
    );
    if (!request) {
      return {
        success: false,
        code: "NOT_FOUND",
        error: RESTOCK_MESSAGES.requestNotFound,
      };
    }
    if (request.status !== UNDECIDED_STATUS) {
      return this.alreadyDecided(request.status, command.action);
    }
    return command.action === "REJECT"
      ? this.reject(request, command)
      : this.approve(request, command);
  }

  private async reject(
    request: RestockRequestForDecision,
    command: RestockRejectCommand,
  ): Promise<RestockLifecycleResult> {
    const isSaved = await this.repository.saveRejection({
      purchaseRequestId: command.id,
      tenantId: command.tenantId,
      actorId: command.actorId,
      decidedAt: new Date(),
      catatan: command.catatan,
    });
    if (!isSaved) return this.decidedMeanwhile(command);

    await logger.logActivity({
      userId: command.actorId,
      tenantId: command.tenantId,
      action: "REJECT PurchaseRequest",
      subject: request.nomorRequest,
      details: {
        id: command.id,
        previousStatus: request.status,
        newStatus: "REJECTED",
        catatan: command.catatan,
      },
    });
    return this.respondWithDecidedRequest(command);
  }

  private async approve(
    request: RestockRequestForDecision,
    command: RestockApproveCommand,
  ): Promise<RestockLifecycleResult> {
    const substituteBarangs = await this.repository.findBarangByIds(
      collectSubstituteIds(command.items),
      command.tenantId,
    );
    const decision = resolveRestockApprovalDecision({
      barangLines: request.barangLines,
      jasaLines: request.jasaLines,
      barangDecisions: command.items,
      jasaDecisions: command.jasaItems,
      substituteBarangs,
    });
    if (decision.success === false) return decision;

    const isSaved = await this.repository.saveApproval({
      purchaseRequestId: command.id,
      tenantId: command.tenantId,
      actorId: command.actorId,
      decidedAt: new Date(),
      catatan: command.catatan?.trim() || null,
      plan: decision.data,
    });
    if (!isSaved) return this.decidedMeanwhile(command);

    const purchaseOrder = await this.safelyGeneratePurchaseOrder(command);
    await this.logApproval(request, command, decision.data, purchaseOrder);

    const updated = await this.repository.findDecidedRequest(
      command.id,
      command.tenantId,
    );
    if (!updated) return this.notFound();
    return {
      success: true,
      data: {
        ...updated,
        _autoGeneratedPO: purchaseOrder.generatedPO
          ? {
              id: purchaseOrder.generatedPO.id,
              poNumber: purchaseOrder.generatedPO.poNumber,
            }
          : null,
        _poError: purchaseOrder.poError,
      },
    };
  }

  private async respondWithDecidedRequest(
    command: RestockLifecycleCommand,
  ): Promise<RestockLifecycleResult> {
    const updated = await this.repository.findDecidedRequest(
      command.id,
      command.tenantId,
    );
    return updated ? { success: true, data: updated } : this.notFound();
  }

  private notFound(): RestockLifecycleResult {
    return {
      success: false,
      code: "NOT_FOUND",
      error: RESTOCK_MESSAGES.requestNotFound,
    };
  }

  private alreadyDecided(
    status: string,
    action: RestockLifecycleCommand["action"],
  ): RestockLifecycleResult {
    return {
      success: false,
      code: "CONFLICT",
      error: restockAlreadyDecidedMessage(
        status,
        LIFECYCLE_DECISION_WORDS[action],
      ),
    };
  }

  /** Pengajuan diputuskan orang lain atau diubah pemohon di antara muat dan simpan. */
  private async decidedMeanwhile(
    command: RestockLifecycleCommand,
  ): Promise<RestockLifecycleResult> {
    const latest = await this.repository.findRequestForDecision(
      command.id,
      command.tenantId,
    );
    if (!latest) return this.notFound();
    if (latest.status !== UNDECIDED_STATUS) {
      return this.alreadyDecided(latest.status, command.action);
    }
    return {
      success: false,
      code: "CONFLICT",
      error: RESTOCK_APPROVAL_MESSAGES.linesChanged,
    };
  }

  private async safelyGeneratePurchaseOrder(
    command: RestockApproveCommand,
  ): Promise<GeneratedPurchaseOrderOutcome> {
    try {
      const generated = await this.purchaseOrderGenerator.generatePOFromPRs(
        [command.id],
        command.actorId,
      );
      return { generatedPO: generated?.[0] ?? null, poError: null };
    } catch (error: unknown) {
      logger.warn("[RESTOCK_APPROVE] PO otomatis gagal dibuat", {
        purchaseRequestId: command.id,
        reason: error instanceof Error ? error.message : String(error),
      });
      return {
        generatedPO: null,
        poError:
          error instanceof SupplierNotActiveError
            ? PO_SUPPLIER_INACTIVE_MESSAGE
            : PO_NOT_GENERATED_MESSAGE,
      };
    }
  }

  private logApproval(
    request: RestockRequestForDecision,
    command: RestockApproveCommand,
    plan: RestockApprovalPlan,
    purchaseOrder: GeneratedPurchaseOrderOutcome,
  ) {
    return logger.logActivity({
      userId: command.actorId,
      tenantId: command.tenantId,
      action: "APPROVE PurchaseRequest",
      subject: request.nomorRequest,
      details: {
        id: command.id,
        previousStatus: request.status,
        newStatus: purchaseOrder.generatedPO ? "ORDERED" : "APPROVED",
        catatan: command.catatan ?? null,
        barang: plan.barangLines.map(describeBarangLineDecision),
        jasa: plan.jasaLines.map(describeLineDecision),
        generatedPO: purchaseOrder.generatedPO?.poNumber ?? null,
        poError: purchaseOrder.poError,
      },
    });
  }
}

function collectSubstituteIds(
  items: RestockApprovalBarangDecision[],
): string[] {
  const ids = items
    .filter((item) => item.keputusan === "APPROVED")
    .map((item) => item.barangIdPengganti)
    .filter((id): id is string => typeof id === "string" && id.length > 0);
  return [...new Set(ids)];
}

function describeLineDecision(line: RestockJasaLinePlan) {
  return {
    itemId: line.itemId,
    nama: line.nama,
    keputusan: line.statusApproval,
    jumlahDiminta: line.quantityChange?.jumlahDiminta ?? null,
    jumlahDisetujui: line.jumlahDisetujui,
    catatan: line.catatanApproval,
  };
}

function describeBarangLineDecision(line: RestockBarangLinePlan) {
  return {
    ...describeLineDecision(line),
    barangIdDiminta: line.substitution?.barangIdDiminta ?? null,
    barangPengganti: line.substitution
      ? { id: line.substitution.barangId, nama: line.substitution.barangNama }
      : null,
  };
}
