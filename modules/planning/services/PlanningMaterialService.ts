/** Item hasil terjemahan rekap, siap di-upsert. */
interface ItemOtomatis {
  sourceKey: string;
  name: string;
  unit: string;
  quantity: number;
  notes: string;
}

const SATUAN_KABEL = "meter";
const SATUAN_SPLITTER = "unit";

/** Catatan asal angka kabel: ukuran mentah dan cadangan yang ditambahkan. */
function susunCatatanKabel(meterTerukur: number, persen: number): string {
  const terukur = `terukur ${meterTerukur} m`;
  return persen > 0 ? `${terukur} + cadangan ${persen}%` : terukur;
}

/** Menerjemahkan rekap kebutuhan menjadi daftar item otomatis. */
function susunItemOtomatis(rekap: KebutuhanMaterialOsp): ItemOtomatis[] {
  const itemKabel = rekap.kabel.map((kabel) => ({
    sourceKey: `kabel:${kabel.jenisFiber}`,
    name: `Kabel ${kabel.jenisFiber}`,
    unit: SATUAN_KABEL,
    quantity: kabel.meterDipesan,
    notes: susunCatatanKabel(kabel.meterTerukur, rekap.spareKabelPersen),
  }));

  const itemSplitter = rekap.splitter.map((splitter) => ({
    sourceKey: `splitter:${splitter.rasio}`,
    name: `Splitter ${splitter.rasio}`,
    unit: SATUAN_SPLITTER,
    quantity: splitter.jumlah,
    notes: `${splitter.jumlah} titik berrasio ${splitter.rasio}`,
  }));

  return [...itemKabel, ...itemSplitter];
}

/**
 * PlanningMaterialService
 *
 * Menutup lingkaran fitur peta: titik dan jalur rencana dihitung menjadi
 * kebutuhan material, lalu diterbitkan sebagai item BOQ yang mengalir ke
 * estimasi budget dan persetujuan berjenjang.
 *
 * Item yang diketik manusia tidak pernah disentuh: penerbitan ulang hanya
 * memperbarui/menghapus item `isAutoGenerated`. Penerbitan mengikuti kunci
 * yang sama dengan BOQ (`canBeEdited`), sehingga material tidak berubah
 * setelah rencana diajukan atau disetujui.
 */
export class PlanningMaterialService {
  constructor(
    private readonly planningRepo: IPlanningRepository,
    private readonly petaRepo: PlanningPetaRepository,
    private readonly itemRepo: IPlanningItemRepository,
    private readonly auditService: PlanningAuditService,
    private readonly unitOfWork: IPlanningUnitOfWork,
  ) {}

  /** Mengambil rencana milik tenant pemanggil (lihat `PlanningItemService`). */
  private async findOwnedPlanning(
    planningId: string,
    tenantId: string,
  ): Promise<PlanningEntity> {
    const planning = await this.planningRepo.findById(planningId);

    if (!planning || planning.tenantId !== tenantId) {
      throw new PlanningNotFoundError();
    }

    return planning;
  }

  /** Material terkunci bersama BOQ: hanya BACKLOG/REJECTED yang boleh berubah. */
  private assertMaterialEditable(planning: PlanningEntity): void {
    if (!planning.canBeEdited()) {
      throw new PlanningInvalidStateError(
        `Material rencana berstatus ${planning.status} tidak bisa diterbitkan ulang. Hanya rencana berstatus BACKLOG atau REJECTED yang bisa diubah.`,
      );
    }
  }

  /** Titik ujung jalur (bisa node nyata) dikelompokkan per id untuk pencarian koordinat. */
  private async petakanTitikJalur(
    titikRencana: MappingNode[],
    idUjung: string[],
    tenantId: string,
  ): Promise<Map<string, MappingNode>> {
    const peta = new Map(titikRencana.map((titik) => [titik.nodeId, titik]));
    const idBelumAda = idUjung.filter((id) => !peta.has(id));

    if (idBelumAda.length > 0) {
      const titikTambahan = await this.petaRepo.ambilTitikByIds(
        idBelumAda,
        tenantId,
      );
      titikTambahan.forEach((titik) => peta.set(titik.nodeId, titik));
    }

    return peta;
  }

  /**
   * Menghitung kebutuhan material dari peta; tidak menulis apa pun.
   *
   * `spareKabelPersen` boleh ditimpa pemanggil supaya perencana bisa
   * menerbitkan dengan cadangan yang baru dia pilih tanpa langkah simpan
   * terpisah. Rentangnya ditegakkan ulang di domain (`pastikanCadanganSah`).
   */
  private async hitungUntukPlanning(
    planning: PlanningEntity,
    spareKabelPersen = planning.spareKabelPersen,
  ): Promise<KebutuhanMaterialOsp> {
    const [titik, jalur] = await Promise.all([
      this.petaRepo.ambilTitikPerPlanning(planning.id),
      this.petaRepo.ambilJalurPerPlanning(planning.id),
    ]);

    const idUjung = jalur.flatMap((edge) => [edge.source, edge.target]);
    const titikPerId = await this.petakanTitikJalur(
      titik,
      idUjung,
      planning.tenantId,
    );

    return hitungKebutuhanMaterialOsp(
      titik.map((node) => PlanningMaterialMapper.toTitikRencana(node)),
      jalur.map((edge) =>
        PlanningMaterialMapper.toJalurRencana(edge, titikPerId),
      ),
      spareKabelPersen,
      calculateHaversineDistance,
    );
  }

  /** Pratinjau kebutuhan material (termasuk `jalurDiabaikan`); tanpa penulisan, berlaku di status apa pun. */
  async hitung(
    planningId: string,
    tenantId: string,
  ): Promise<KebutuhanMaterialOsp> {
    const planning = await this.findOwnedPlanning(planningId, tenantId);
    return this.hitungUntukPlanning(planning);
  }

  /**
   * Menerbitkan rekap menjadi item material otomatis dalam satu transaksi:
   * upsert per `sourceKey`, hapus item otomatis yang tak lagi muncul, tulis audit.
   * Idempoten; item manual tidak tersentuh. Ditolak bila rencana sudah terkunci.
   */
  async terbitkan(
    planningId: string,
    userId: string,
    tenantId: string,
    spareKabelPersenBaru?: number,
  ): Promise<PlanningItemDTO[]> {
    const planning = await this.findOwnedPlanning(planningId, tenantId);
    this.assertMaterialEditable(planning);

    const rekap = await this.hitungUntukPlanning(
      planning,
      spareKabelPersenBaru,
    );
    const daftarItem = susunItemOtomatis(rekap);
    const sourceKeyDipakai = daftarItem.map((item) => item.sourceKey);
    const cadanganBerubah =
      spareKabelPersenBaru !== undefined &&
      spareKabelPersenBaru !== planning.spareKabelPersen;

    const diterbitkan = await this.unitOfWork.runInTransaction(async (tx) => {
      // Cadangan yang dipakai disimpan bersama item yang lahir darinya.
      // Tanpa ini panel akan membuka kembali dengan angka lama, sementara
      // item material sudah memakai angka yang baru.
      if (cadanganBerubah) {
        await this.planningRepo.update(
          planningId,
          { spareKabelPersen: spareKabelPersenBaru },
          tx,
        );
      }

      const hasil = [];
      for (const item of daftarItem) {
        hasil.push(
          await this.itemRepo.upsertBySourceKey(
            {
              planningId,
              tenantId: planning.tenantId,
              isAutoGenerated: true,
              ...item,
            },
            tx,
          ),
        );
      }

      const jumlahDihapus = await this.itemRepo.hapusOtomatisYangTidakDipakai(
        { planningId, isAutoGenerated: true, sourceKeyDipakai },
        tx,
      );

      await this.auditService.logChange(
        {
          planningId,
          tenantId: planning.tenantId,
          action: "ITEM_UPDATED",
          performedById: userId,
          changes: {
            sumber: "peta",
            sourceKeys: sourceKeyDipakai,
            jumlahDihapus,
            jalurDiabaikan: rekap.jalurDiabaikan,
            spareKabelPersen: rekap.spareKabelPersen,
          },
          notes: "Material diterbitkan dari titik dan jalur peta rencana",
        },
        tx,
      );

      return hasil;
    });

    logger.logActivity({
      action: "planning.material_published",
      subject: "PlanningItem",
      details: {
        planningId,
        jumlahItem: diterbitkan.length,
        jalurDiabaikan: rekap.jalurDiabaikan,
      },
      userId,
      tenantId: planning.tenantId,
    });

    return diterbitkan.map((item) => PlanningItemMapper.toDTO(item));
  }
}
