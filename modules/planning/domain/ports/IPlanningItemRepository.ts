import type { PlanningItemEntity } from "../entities/PlanningItemEntity";

import type { TransactionClient } from "./IPlanningRepository";

export interface CreatePlanningItemInput {
  planningId: string;
  tenantId: string;
  name: string;
  description?: string | null;
  quantity: number;
  unit: string;
  estimatedPrice?: number | null;
  actualPrice?: number | null;
  notes?: string | null;
}

export interface UpdatePlanningItemInput {
  name?: string;
  description?: string | null;
  quantity?: number;
  unit?: string;
  estimatedPrice?: number | null;
  actualPrice?: number | null;
  notes?: string | null;
}

/** Item otomatis dari rekap peta; dikenali lewat `sourceKey`. */
export interface UpsertPlanningItemBySourceKeyInput {
  planningId: string;
  tenantId: string;
  sourceKey: string;
  name: string;
  unit: string;
  quantity: number;
  notes: string;
  isAutoGenerated: true;
}

/** Penyaring penghapusan item otomatis yang kuncinya tak lagi muncul. */
export interface HapusItemOtomatisFilter {
  planningId: string;
  isAutoGenerated: true;
  sourceKeyDipakai: string[];
}

export interface FindAllPlanningItemFilters {
  tenantId?: string | null;
  planningId?: string;
  page?: number;
  limit?: number;
}

export interface IPlanningItemRepository {
  /**
   * Find planning item by ID
   */
  findById(id: string): Promise<PlanningItemEntity | null>;

  /**
   * Find all planning items with filters and pagination
   */
  findAll(
    filters: FindAllPlanningItemFilters,
  ): Promise<{ items: PlanningItemEntity[]; total: number }>;

  /**
   * Find all items for a specific planning
   */
  findByPlanningId(planningId: string): Promise<PlanningItemEntity[]>;

  /**
   * Create new planning item
   */
  create(
    data: CreatePlanningItemInput,
    tx?: TransactionClient,
  ): Promise<PlanningItemEntity>;

  /**
   * Update planning item
   */
  update(
    id: string,
    data: UpdatePlanningItemInput,
    tx?: TransactionClient,
  ): Promise<PlanningItemEntity>;

  /**
   * Delete planning item
   */
  delete(id: string, tx?: TransactionClient): Promise<void>;

  /**
   * Delete all items for a specific planning (cascade delete)
   */
  deleteByPlanningId(planningId: string, tx?: TransactionClient): Promise<void>;

  /**
   * Membuat atau memperbarui item otomatis berdasarkan `sourceKey`.
   * Hanya menyentuh item `isAutoGenerated`; harga yang diisi manusia tidak ditimpa.
   */
  upsertBySourceKey(
    data: UpsertPlanningItemBySourceKeyInput,
    tx?: TransactionClient,
  ): Promise<PlanningItemEntity>;

  /**
   * Menghapus item otomatis yang `sourceKey`-nya tidak lagi dipakai.
   * Item manual tidak pernah ikut terhapus. Mengembalikan jumlah terhapus.
   */
  hapusOtomatisYangTidakDipakai(
    filter: HapusItemOtomatisFilter,
    tx?: TransactionClient,
  ): Promise<number>;
}
