import { describe, it, expect, vi, beforeEach } from "vitest";
import type { Prisma } from "@prisma/client";

import { PlanningItemRepository } from "@/modules/planning/repositories/PlanningItemRepository";

const { mockFindFirst, mockUpsert, mockDeleteMany } = vi.hoisted(() => ({
  mockFindFirst: vi.fn(),
  mockUpsert: vi.fn(),
  mockDeleteMany: vi.fn(),
}));

vi.mock("@/lib/prisma", () => ({ prisma: {} }));

const now = new Date("2026-10-11T00:00:00.000Z");

function barisItem(overrides: Record<string, unknown> = {}) {
  return {
    id: "item-1",
    planningId: "plan-1",
    tenantId: "tenant-1",
    name: "Kabel feeder",
    description: null as string | null,
    quantity: 220,
    unit: "meter",
    estimatedPrice: null as number | null,
    actualPrice: null as number | null,
    notes: "terukur 200 m + cadangan 10%",
    isAutoGenerated: true,
    sourceKey: "kabel:feeder",
    createdAt: now,
    updatedAt: now,
    ...overrides,
  };
}

const tx = {
  planningItem: {
    findFirst: mockFindFirst,
    upsert: mockUpsert,
    deleteMany: mockDeleteMany,
  },
} as unknown as Prisma.TransactionClient;

const masukan = {
  planningId: "plan-1",
  tenantId: "tenant-1",
  sourceKey: "kabel:feeder",
  name: "Kabel feeder",
  unit: "meter",
  quantity: 220,
  notes: "terukur 200 m + cadangan 10%",
  isAutoGenerated: true as const,
};

describe("PlanningItemRepository item otomatis", () => {
  let repo: PlanningItemRepository;

  beforeEach(() => {
    vi.clearAllMocks();
    repo = new PlanningItemRepository();
    mockUpsert.mockResolvedValue(barisItem());
  });

  describe("hapusOtomatisYangTidakDipakai", () => {
    it("menyaring planningId, isAutoGenerated tetap true, dan kunci yang tak dipakai", async () => {
      mockDeleteMany.mockResolvedValue({ count: 3 });

      const jumlah = await repo.hapusOtomatisYangTidakDipakai(
        {
          planningId: "plan-1",
          isAutoGenerated: true,
          sourceKeyDipakai: ["kabel:feeder"],
        },
        tx,
      );

      expect(jumlah).toBe(3);
      expect(mockDeleteMany).toHaveBeenCalledWith({
        where: {
          planningId: "plan-1",
          isAutoGenerated: true,
          OR: [{ sourceKey: null }, { sourceKey: { notIn: ["kabel:feeder"] } }],
        },
      });
    });

    it("tetap menulis isAutoGenerated true walau pemanggil mengirim nilai lain", async () => {
      mockDeleteMany.mockResolvedValue({ count: 0 });

      await repo.hapusOtomatisYangTidakDipakai(
        {
          planningId: "plan-1",
          isAutoGenerated: false as unknown as true,
          sourceKeyDipakai: [],
        },
        tx,
      );

      expect(mockDeleteMany.mock.calls[0][0].where.isAutoGenerated).toBe(true);
    });

    it("meneruskan daftar kunci kosong apa adanya", async () => {
      mockDeleteMany.mockResolvedValue({ count: 0 });

      await repo.hapusOtomatisYangTidakDipakai(
        { planningId: "plan-1", isAutoGenerated: true, sourceKeyDipakai: [] },
        tx,
      );

      expect(mockDeleteMany.mock.calls[0][0].where.OR).toEqual([
        { sourceKey: null },
        { sourceKey: { notIn: [] } },
      ]);
    });
  });

  describe("upsertBySourceKey", () => {
    /**
     * Penjaga konkurensi yang sebenarnya ada di basis data: kunci unik
     * `(planningId, sourceKey)`. Versi `findFirst` + `create`/`update`
     * membuat dua penerbitan yang tumpang-tindih sama-sama tidak menemukan
     * baris lalu sama-sama membuatnya — item material ganda yang menetap dan
     * membuat estimasi budget terhitung dobel. Kalau pencarian itu kembali,
     * tes ini merah.
     */
    it("memakai satu upsert di atas kunci unik, tanpa membaca lebih dulu", async () => {
      await repo.upsertBySourceKey(masukan, tx);

      expect(mockFindFirst).not.toHaveBeenCalled();
      expect(mockUpsert).toHaveBeenCalledTimes(1);
      expect(mockUpsert.mock.calls[0][0].where).toEqual({
        planningId_sourceKey: {
          planningId: "plan-1",
          sourceKey: "kabel:feeder",
        },
      });
    });

    it("cabang update hanya mengubah name, unit, quantity, notes", async () => {
      await repo.upsertBySourceKey(masukan, tx);

      expect(mockUpsert.mock.calls[0][0].update).toEqual({
        name: "Kabel feeder",
        unit: "meter",
        quantity: 220,
        notes: "terukur 200 m + cadangan 10%",
      });
      const update = mockUpsert.mock.calls[0][0].update;
      expect(update).not.toHaveProperty("estimatedPrice");
      expect(update).not.toHaveProperty("description");
      // isAutoGenerated tidak ikut diubah: baris yang sudah ada memang sudah
      // otomatis, dan menulisnya di cabang update berarti baris manual yang
      // (secara hipotetis) menempati kunci ini akan dirampas.
      expect(update).not.toHaveProperty("isAutoGenerated");
    });

    it("cabang create selalu menulis isAutoGenerated true", async () => {
      await repo.upsertBySourceKey(
        { ...masukan, isAutoGenerated: false as unknown as true },
        tx,
      );

      expect(mockUpsert.mock.calls[0][0].create).toEqual({
        planningId: "plan-1",
        tenantId: "tenant-1",
        sourceKey: "kabel:feeder",
        name: "Kabel feeder",
        unit: "meter",
        quantity: 220,
        notes: "terukur 200 m + cadangan 10%",
        isAutoGenerated: true,
      });
    });
  });
});
