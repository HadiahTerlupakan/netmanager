function itemEntity(sourceKey: string): PlanningItemEntity {
  return new PlanningItemEntity({
    id: `item-${sourceKey}`,
    planningId: "plan-1",
    tenantId: "tenant-1",
    name: sourceKey,
    description: null,
    quantity: 1,
    unit: "unit",
    estimatedPrice: null,
    actualPrice: null,
    notes: null,
    createdAt: now,
    updatedAt: now,
    isAutoGenerated: true,
    sourceKey,
  });
}

describe("PlanningMaterialService", () => {
  let service: PlanningMaterialService;
  let planningRepo: Mocked<IPlanningRepository>;
  let petaRepo: Mocked<PlanningPetaRepository>;
  let itemRepo: Mocked<IPlanningItemRepository>;
  let audit: Mocked<PlanningAuditService>;

  beforeEach(() => {
    vi.clearAllMocks();

    planningRepo = {
      findById: vi.fn().mockResolvedValue(planning()),
      update: vi.fn().mockResolvedValue(planning()),
    } as unknown as Mocked<IPlanningRepository>;

    petaRepo = {
      ambilTitikPerPlanning: vi
        .fn()
        .mockResolvedValue([node(), node({ nodeId: "n-2" })]),
      ambilJalurPerPlanning: vi.fn().mockResolvedValue([edge()]),
      ambilTitikByIds: vi.fn().mockResolvedValue([]),
    } as unknown as Mocked<PlanningPetaRepository>;

    itemRepo = {
      upsertBySourceKey: vi
        .fn()
        .mockImplementation(async (data) => itemEntity(data.sourceKey)),
      hapusOtomatisYangTidakDipakai: vi.fn().mockResolvedValue(0),
    } as unknown as Mocked<IPlanningItemRepository>;

    audit = { logChange: vi.fn() } as unknown as Mocked<PlanningAuditService>;

    service = new PlanningMaterialService(
      planningRepo,
      petaRepo,
      itemRepo,
      audit,
      createFakeUnitOfWork(),
    );
  });

  describe("terbitkan", () => {
    it("membuat item kabel dengan jumlah siap pesan dan asal angkanya", async () => {
      await service.terbitkan("plan-1", "user-1", "tenant-1");

      expect(itemRepo.upsertBySourceKey).toHaveBeenCalledWith(
        expect.objectContaining({
          planningId: "plan-1",
          tenantId: "tenant-1",
          sourceKey: "kabel:feeder",
          name: "Kabel feeder",
          unit: "meter",
          quantity: 220,
          isAutoGenerated: true,
          notes: "terukur 200 m + cadangan 10%",
        }),
        undefined,
      );
    });

    it("menulis catatan tanpa cadangan bila cadangan 0", async () => {
      planningRepo.findById.mockResolvedValue(planning("BACKLOG", 0));

      await service.terbitkan("plan-1", "user-1", "tenant-1");

      expect(itemRepo.upsertBySourceKey).toHaveBeenCalledWith(
        expect.objectContaining({ quantity: 200, notes: "terukur 200 m" }),
        undefined,
      );
    });

    it("membuat item splitter per rasio", async () => {
      await service.terbitkan("plan-1", "user-1", "tenant-1");

      expect(itemRepo.upsertBySourceKey).toHaveBeenCalledWith(
        expect.objectContaining({
          sourceKey: "splitter:1:8",
          name: "Splitter 1:8",
          unit: "unit",
          quantity: 2,
        }),
        undefined,
      );
    });

    it("tidak pernah menyentuh item yang diketik manusia", async () => {
      await service.terbitkan("plan-1", "user-1", "tenant-1");

      const filter = itemRepo.hapusOtomatisYangTidakDipakai.mock.calls[0][0];
      expect(filter.isAutoGenerated).toBe(true);
      expect(filter.planningId).toBe("plan-1");
      for (const [data] of itemRepo.upsertBySourceKey.mock.calls) {
        expect(data.isAutoGenerated).toBe(true);
      }
    });

    it("menghapus hanya item otomatis yang kuncinya tak lagi muncul", async () => {
      await service.terbitkan("plan-1", "user-1", "tenant-1");

      const filter = itemRepo.hapusOtomatisYangTidakDipakai.mock.calls[0][0];
      expect(filter.sourceKeyDipakai).toEqual(["kabel:feeder", "splitter:1:8"]);
    });

    it("idempoten: menerbitkan dua kali memakai kunci yang sama", async () => {
      await service.terbitkan("plan-1", "user-1", "tenant-1");
      await service.terbitkan("plan-1", "user-1", "tenant-1");

      const kunci = itemRepo.upsertBySourceKey.mock.calls.map(
        (panggilan) => panggilan[0].sourceKey,
      );
      expect(kunci).toHaveLength(4);
      expect(new Set(kunci).size).toBe(kunci.length / 2);
    });

    it.each<PlanningStatus>([
      "PENDING_APPROVAL",
      "APPROVED_LEVEL1",
      "APPROVED",
      "IN_PROGRESS",
      "COMPLETED",
      "CANCELLED",
    ])(
      "menolak menerbitkan material pada planning berstatus %s",
      async (status) => {
        // Material yang berubah setelah diajukan/disetujui berarti yang
        // disetujui direksi bukan yang dibeli.
        planningRepo.findById.mockResolvedValue(planning(status));

        await expect(
          service.terbitkan("plan-1", "user-1", "tenant-1"),
        ).rejects.toBeInstanceOf(PlanningInvalidStateError);
        expect(itemRepo.upsertBySourceKey).not.toHaveBeenCalled();
        expect(itemRepo.hapusOtomatisYangTidakDipakai).not.toHaveBeenCalled();
        expect(audit.logChange).not.toHaveBeenCalled();
      },
    );

    it.each<PlanningStatus>(["BACKLOG", "REJECTED"])(
      "mengizinkan menerbitkan pada planning berstatus %s",
      async (status) => {
        planningRepo.findById.mockResolvedValue(planning(status));

        await expect(
          service.terbitkan("plan-1", "user-1", "tenant-1"),
        ).resolves.toHaveLength(2);
      },
    );

    it("planning tanpa titik dan jalur: tidak meng-upsert, menghapus semua item otomatis", async () => {
      petaRepo.ambilTitikPerPlanning.mockResolvedValue([]);
      petaRepo.ambilJalurPerPlanning.mockResolvedValue([]);

      await expect(
        service.terbitkan("plan-1", "user-1", "tenant-1"),
      ).resolves.toEqual([]);

      expect(itemRepo.upsertBySourceKey).not.toHaveBeenCalled();
      expect(itemRepo.hapusOtomatisYangTidakDipakai).toHaveBeenCalledWith(
        { planningId: "plan-1", isAutoGenerated: true, sourceKeyDipakai: [] },
        undefined,
      );
    });

    it("menolak planning milik tenant lain sebagai tidak ditemukan", async () => {
      planningRepo.findById.mockResolvedValue(
        planning("BACKLOG", 10, "tenant-lain"),
      );

      await expect(
        service.terbitkan("plan-1", "user-1", "tenant-1"),
      ).rejects.toBeInstanceOf(PlanningNotFoundError);
    });

    it("memakai cadangan yang dikirim pemanggil, bukan yang tersimpan", async () => {
      // Perencana mengubah persentase di panel lalu langsung menekan tombol;
      // bila angka itu tidak ikut, item yang dibeli memakai cadangan lama.
      await service.terbitkan("plan-1", "user-1", "tenant-1", 25);

      expect(itemRepo.upsertBySourceKey).toHaveBeenCalledWith(
        expect.objectContaining({
          sourceKey: "kabel:feeder",
          quantity: 250,
          notes: "terukur 200 m + cadangan 25%",
        }),
        undefined,
      );
    });

    it("menyimpan cadangan baru dalam transaksi yang sama", async () => {
      await service.terbitkan("plan-1", "user-1", "tenant-1", 25);

      expect(planningRepo.update).toHaveBeenCalledWith(
        "plan-1",
        { spareKabelPersen: 25 },
        undefined,
      );
    });

    it("tidak menyentuh rencana bila cadangan tidak berubah atau tidak dikirim", async () => {
      await service.terbitkan("plan-1", "user-1", "tenant-1");
      await service.terbitkan("plan-1", "user-1", "tenant-1", 10);

      expect(planningRepo.update).not.toHaveBeenCalled();
    });

    it("menolak cadangan di luar rentang tanpa menulis apa pun", async () => {
      await expect(
        service.terbitkan("plan-1", "user-1", "tenant-1", 101),
      ).rejects.toThrow(/cadangan kabel/i);

      expect(itemRepo.upsertBySourceKey).not.toHaveBeenCalled();
      expect(planningRepo.update).not.toHaveBeenCalled();
    });

    it("menulis audit saat material diterbitkan, termasuk jalur yang diabaikan", async () => {
      petaRepo.ambilJalurPerPlanning.mockResolvedValue([
        edge({ distance: null, source: "n-x", target: "n-y" }),
      ]);

      await service.terbitkan("plan-1", "user-1", "tenant-1");

      expect(audit.logChange).toHaveBeenCalledWith(
        expect.objectContaining({
          planningId: "plan-1",
          tenantId: "tenant-1",
          action: "ITEM_UPDATED",
          performedById: "user-1",
          changes: expect.objectContaining({ jalurDiabaikan: 1 }),
        }),
        undefined,
      );
    });

    /**
     * Dulu jalur ini dihitung sebagai garis lurus ujung-ke-ujung: lebih
     * pendek dari kenyataan, dan TIDAK masuk `jalurDiabaikan`. Satu-satunya
     * jalan yang masih membuat meter kabel hilang tanpa jejak.
     */
    it("mengabaikan jalur berwaypoint rusak dan mencatatnya di jalurDiabaikan", async () => {
      petaRepo.ambilTitikPerPlanning.mockResolvedValue([
        node({ nodeId: "n-1", latitude: -6.2, longitude: 106.8 }),
        node({ nodeId: "n-2", latitude: -6.21, longitude: 106.8 }),
      ]);
      petaRepo.ambilJalurPerPlanning.mockResolvedValue([
        edge({ distance: null, waypoints: "{bukan json" }),
      ]);

      await service.terbitkan("plan-1", "user-1", "tenant-1");

      const kabel = itemRepo.upsertBySourceKey.mock.calls
        .map((panggilan) => panggilan[0])
        .find((data) => data.sourceKey === "kabel:feeder");
      expect(kabel).toBeUndefined();
      expect(audit.logChange).toHaveBeenCalledWith(
        expect.objectContaining({
          changes: expect.objectContaining({ jalurDiabaikan: 1 }),
        }),
        undefined,
      );
    });

    it("membaca koordinat ujung jalur yang berupa node nyata", async () => {
      petaRepo.ambilTitikPerPlanning.mockResolvedValue([
        node({ nodeId: "n-1", latitude: -6.2, longitude: 106.8 }),
      ]);
      petaRepo.ambilTitikByIds.mockResolvedValue([
        node({
          nodeId: "n-2",
          isPlanned: false,
          planningId: null,
          latitude: -6.21,
          longitude: 106.8,
        }),
      ]);
      petaRepo.ambilJalurPerPlanning.mockResolvedValue([
        edge({ distance: null }),
      ]);

      await service.terbitkan("plan-1", "user-1", "tenant-1");

      expect(petaRepo.ambilTitikByIds).toHaveBeenCalledWith(
        ["n-2"],
        "tenant-1",
      );
      const kabel = itemRepo.upsertBySourceKey.mock.calls
        .map((panggilan) => panggilan[0])
        .find((data) => data.sourceKey === "kabel:feeder");
      expect(kabel?.quantity).toBeGreaterThan(1000);
    });
  });

  describe("hitung", () => {
    it("meneruskan jalurDiabaikan dan tidak menulis apa pun", async () => {
      petaRepo.ambilJalurPerPlanning.mockResolvedValue([
        edge({ distance: null, source: "n-x", target: "n-y" }),
      ]);

      const rekap = await service.hitung("plan-1", "tenant-1");

      expect(rekap.jalurDiabaikan).toBe(1);
      expect(itemRepo.upsertBySourceKey).not.toHaveBeenCalled();
      expect(audit.logChange).not.toHaveBeenCalled();
    });

    it("tetap bisa dipratinjau pada planning yang sudah disetujui", async () => {
      planningRepo.findById.mockResolvedValue(planning("APPROVED"));

      const rekap = await service.hitung("plan-1", "tenant-1");

      expect(rekap.kabel[0]).toEqual({
        jenisFiber: "feeder",
        meterTerukur: 200,
        meterDipesan: 220,
      });
    });

    it("menolak planning milik tenant lain", async () => {
      planningRepo.findById.mockResolvedValue(
        planning("BACKLOG", 10, "tenant-lain"),
      );

      await expect(service.hitung("plan-1", "tenant-1")).rejects.toBeInstanceOf(
        PlanningNotFoundError,
      );
    });
  });
});

describe("uraikanWaypoints", () => {
  it("menguraikan JSON pasangan koordinat", () => {
    expect(uraikanWaypoints("[[-6.2,106.8],[-6.3,106.9]]")).toEqual([
      [-6.2, 106.8],
      [-6.3, 106.9],
    ]);
  });

  it.each([null, "", "[]"])(
    "memperlakukan %j sebagai jalur tanpa titik belok",
    (mentah) => {
      expect(uraikanWaypoints(mentah)).toEqual([]);
    },
  );

  // `null` dibedakan dari `[]` dengan sengaja: baris rusak tidak boleh
  // diperlakukan sebagai jalur lurus, karena panjangnya akan terhitung lebih
  // pendek dari kenyataan tanpa ada yang menyadarinya.
  it.each([
    "{bukan json",
    '{"a":1}',
    "[[1]]",
    '[["a","b"]]',
    "[[null,106.8]]",
    '[["-6.2","106.8"]]',
  ])("melaporkan %j sebagai rusak, bukan kosong", (mentah) => {
    expect(uraikanWaypoints(mentah)).toBeNull();
  });
});
