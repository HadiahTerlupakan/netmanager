import { NextRequest } from "next/server";
import { beforeEach, describe, expect, it, vi } from "vitest";

const mocks = vi.hoisted(() => ({
  getServerSession: vi.fn(),
  hasPermission: vi.fn(),
  ensureSiteAccess: vi.fn(),
  patchLifecycle: vi.fn(),
  loggerError: vi.fn(),
}));

vi.mock("next-auth", () => ({ getServerSession: mocks.getServerSession }));
vi.mock("@/lib/auth", () => ({ authOptions: {} }));
vi.mock("@/lib/rbac", () => ({ hasPermission: mocks.hasPermission }));
vi.mock("@/lib/logger", () => ({
  logger: { error: mocks.loggerError, warn: vi.fn(), logActivity: vi.fn() },
}));
vi.mock("@/app/api/inventory/restock/_lib/restock-site-access", () => ({
  ensureRestockRequestSiteAccess: mocks.ensureSiteAccess,
  ensureRestockGudangSiteAccess: vi.fn(),
}));
vi.mock("@/modules/inventory", async () => {
  const messages = await vi.importActual<
    typeof import("@/modules/inventory/services/restock-messages")
  >("@/modules/inventory/services/restock-messages");
  return {
    ...messages,
    patchRestockRequestLifecycle: mocks.patchLifecycle,
    getRestockRequestDetail: vi.fn(),
    getInventoryRouteService: vi.fn(() => ({})),
  };
});
vi.mock("@/modules/procurement", () => ({
  getPurchaseOrderService: vi.fn(),
  PurchaseOrderNotFoundError: class extends Error {},
  PurchaseOrderNotEditableError: class extends Error {},
}));

import { PATCH } from "@/app/api/inventory/restock/requests/[id]/route";

function patch(body: unknown) {
  return PATCH(
    new NextRequest("http://localhost/api/inventory/restock/requests/pr-1", {
      method: "PATCH",
      body: JSON.stringify(body),
    }),
    { params: Promise.resolve({ id: "pr-1" }) },
  );
}

const validApprove = {
  action: "APPROVE",
  items: [{ itemId: "item-1", keputusan: "APPROVED", jumlah: 3 }],
};

describe("PATCH /api/inventory/restock/requests/[id]", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mocks.getServerSession.mockResolvedValue({
      user: { id: "user-1", tenantId: "tenant-1" },
    });
    mocks.hasPermission.mockResolvedValue(true);
    mocks.ensureSiteAccess.mockResolvedValue(null);
  });

  it("menolak akun tanpa izin restock:approve", async () => {
    mocks.hasPermission.mockImplementation(
      async (permission: string) => permission !== "restock:approve",
    );

    const response = await patch(validApprove);

    expect(response.status).toBe(403);
    expect((await response.json()).error).toContain(
      "menyetujui pengajuan restock",
    );
    expect(mocks.patchLifecycle).not.toHaveBeenCalled();
  });

  it("menolak penolakan tanpa alasan dengan 400", async () => {
    const response = await patch({ action: "REJECT", catatan: "  " });

    expect(response.status).toBe(400);
    expect((await response.json()).error).toBe(
      "Alasan penolakan belum diisi. Tulis kenapa ditolak.",
    );
    expect(mocks.patchLifecycle).not.toHaveBeenCalled();
  });

  it("menolak baris disetujui tanpa jumlah dengan 400", async () => {
    const response = await patch({
      action: "APPROVE",
      items: [{ itemId: "item-1", keputusan: "APPROVED" }],
    });

    expect(response.status).toBe(400);
    expect((await response.json()).error).toContain("Barang ke-1");
  });

  it("menolak tindakan yang tidak dikenal dengan 400", async () => {
    const response = await patch({ action: "SUBMIT" });

    expect(response.status).toBe(400);
  });

  it.each([
    ["INVALID", 400],
    ["NOT_FOUND", 404],
    ["CONFLICT", 409],
  ])("memetakan galat %s ke status %i", async (code, status) => {
    mocks.patchLifecycle.mockResolvedValue({
      success: false,
      code,
      error: "Pesan untuk penyetuju",
    });

    const response = await patch(validApprove);

    expect(response.status).toBe(status);
    expect(await response.json()).toEqual({ error: "Pesan untuk penyetuju" });
  });

  it("mengirim isi pengajuan beserta hasil PO apa adanya", async () => {
    const data = {
      id: "pr-1",
      status: "ORDERED",
      _autoGeneratedPO: { id: "po-1", poNumber: "PO/1" },
      _poError: null as string | null,
    };
    mocks.patchLifecycle.mockResolvedValue({ success: true, data });

    const response = await patch({ ...validApprove, catatan: " Oke " });

    expect(response.status).toBe(200);
    expect(await response.json()).toEqual(data);
    expect(mocks.patchLifecycle).toHaveBeenCalledWith({
      action: "APPROVE",
      catatan: "Oke",
      items: validApprove.items,
      jasaItems: [],
      id: "pr-1",
      tenantId: "tenant-1",
      actorId: "user-1",
    });
  });

  it("mengembalikan 500 dengan pesan gangguan bila service gagal tak terduga", async () => {
    mocks.patchLifecycle.mockRejectedValue(new Error("db down"));

    const response = await patch(validApprove);

    expect(response.status).toBe(500);
    expect((await response.json()).error).toContain("Memproses pengajuan");
    expect(mocks.loggerError).toHaveBeenCalled();
  });
});
