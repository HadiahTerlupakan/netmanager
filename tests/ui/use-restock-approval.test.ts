import { beforeEach, describe, expect, it, vi } from "vitest";

import type { PurchaseRequest } from "@/app/admin/inventory/restock/types";

const mockUseState = vi.fn();
const mockPatchWithAuth = vi.fn();
const mockToastSuccess = vi.fn();
const mockToastError = vi.fn();
const mockToast = vi.fn();

vi.mock("react", async () => {
  const actual = await vi.importActual<typeof import("react")>("react");
  return {
    ...actual,
    useState: ((initial: unknown) =>
      mockUseState(initial)) as typeof actual.useState,
    useCallback: ((fn: unknown) => fn) as typeof actual.useCallback,
    useMemo: ((factory: () => unknown) => factory()) as typeof actual.useMemo,
  };
});

vi.mock("@/lib/api-client", () => ({
  patchWithAuth: (...args: unknown[]) => mockPatchWithAuth(...args),
}));

vi.mock("react-hot-toast", () => ({
  toast: Object.assign((...args: unknown[]) => mockToast(...args), {
    success: (...args: unknown[]) => mockToastSuccess(...args),
    error: (...args: unknown[]) => mockToastError(...args),
  }),
}));

import { buildInitialApprovalDecisions } from "@/app/admin/inventory/restock/approvalUtils";
import { useRestockApproval } from "@/app/admin/inventory/restock/useRestockApproval";

const request: PurchaseRequest = {
  id: "pr-1",
  nomorRequest: "PR-001",
  status: "DRAFT",
  createdAt: "2026-11-01T00:00:00.000Z",
  requester: { name: "Rohadim" },
  gudangId: "gudang-a",
  gudang: { id: "gudang-a", nama: "Gudang A" },
  items: [
    {
      id: "item-1",
      barangId: "barang-1",
      jumlah: 10,
      receivedQuantity: 0,
      barang: { nama: "Kabel Fiber", kode: "BRG-1", satuan: "roll" },
    },
  ],
};

/** Urutan useState di useRestockApproval. */
const STATE_REQUEST = 1;
const STATE_DECISIONS = 2;
const STATE_OVERALL_NOTE = 3;

function useApprovalHookWithState(overrides: Map<number, unknown>) {
  const setters: Array<ReturnType<typeof vi.fn>> = [];
  let index = 0;
  mockUseState.mockImplementation((initial: unknown) => {
    index += 1;
    const setter = vi.fn();
    setters.push(setter);
    return [overrides.has(index) ? overrides.get(index) : initial, setter];
  });
  const fetchData = vi.fn().mockResolvedValue(undefined);
  const hook = useRestockApproval({ fetchData, allBarangs: [] });
  return { hook, fetchData, setters };
}

describe("useRestockApproval", () => {
  beforeEach(() => {
    mockUseState.mockReset();
    mockPatchWithAuth.mockReset();
    mockToastSuccess.mockClear();
    mockToastError.mockClear();
    mockToast.mockClear();
  });

  it("sends per-line decisions to the PATCH endpoint and refetches", async () => {
    const decisions = buildInitialApprovalDecisions(request);
    decisions.items["item-1"].jumlah = 8;
    decisions.items["item-1"].catatan = "Cukup 8";
    mockPatchWithAuth.mockResolvedValue({
      ok: true,
      json: async (): Promise<Record<string, unknown>> => ({
        id: "pr-1",
        _autoGeneratedPO: null,
        _poError: null,
      }),
    });
    const { hook, fetchData } = useApprovalHookWithState(
      new Map<number, unknown>([
        [STATE_REQUEST, request],
        [STATE_DECISIONS, decisions],
        [STATE_OVERALL_NOTE, " Oke "],
      ]),
    );

    await hook.approve();

    expect(mockPatchWithAuth).toHaveBeenCalledWith(
      "/api/inventory/restock/requests/pr-1",
      {
        action: "APPROVE",
        catatan: "Oke",
        items: [
          {
            itemId: "item-1",
            keputusan: "APPROVED",
            jumlah: 8,
            catatan: "Cukup 8",
          },
        ],
        jasaItems: [],
      },
    );
    expect(mockToastSuccess).toHaveBeenCalledWith("Pengajuan disetujui");
    expect(fetchData).toHaveBeenCalled();
  });

  it("keeps the PO warning toast when auto PO generation failed", async () => {
    mockPatchWithAuth.mockResolvedValue({
      ok: true,
      json: async () => ({ _poError: "Supplier tidak aktif" }),
    });
    const { hook } = useApprovalHookWithState(
      new Map<number, unknown>([
        [STATE_REQUEST, request],
        [STATE_DECISIONS, buildInitialApprovalDecisions(request)],
      ]),
    );

    await hook.approve();

    expect(mockToast).toHaveBeenCalledWith(
      "Supplier tidak aktif",
      expect.objectContaining({ duration: 12_000 }),
    );
    expect(mockToastSuccess).not.toHaveBeenCalled();
  });

  it("does not submit while problems remain", async () => {
    const decisions = buildInitialApprovalDecisions(request);
    decisions.items["item-1"].keputusan = "REJECTED";
    const { hook } = useApprovalHookWithState(
      new Map<number, unknown>([
        [STATE_REQUEST, request],
        [STATE_DECISIONS, decisions],
      ]),
    );

    await hook.approve();

    expect(mockPatchWithAuth).not.toHaveBeenCalled();
    expect(mockToastError).toHaveBeenCalledWith(
      expect.stringContaining("Pengajuan belum bisa disetujui:"),
      expect.anything(),
    );
  });

  it("rejects the whole request with the overall note", async () => {
    mockPatchWithAuth.mockResolvedValue({
      ok: true,
      json: async () => ({ id: "pr-1", status: "REJECTED" }),
    });
    const { hook } = useApprovalHookWithState(
      new Map<number, unknown>([
        [STATE_REQUEST, request],
        [STATE_DECISIONS, buildInitialApprovalDecisions(request)],
        [STATE_OVERALL_NOTE, "Anggaran habis"],
      ]),
    );

    await hook.reject();

    expect(mockPatchWithAuth).toHaveBeenCalledWith(
      "/api/inventory/restock/requests/pr-1",
      { action: "REJECT", catatan: "Anggaran habis" },
    );
    expect(mockToastSuccess).toHaveBeenCalledWith("Pengajuan ditolak");
  });

  it("refuses to reject without an overall note", async () => {
    const { hook } = useApprovalHookWithState(
      new Map<number, unknown>([[STATE_REQUEST, request]]),
    );

    await hook.reject();

    expect(mockPatchWithAuth).not.toHaveBeenCalled();
    expect(mockToastError).toHaveBeenCalledWith(
      "Tulis alasan penolakan di catatan keputusan.",
      expect.anything(),
    );
  });

  it("closes the stale modal and reloads the list on a 409 conflict", async () => {
    mockPatchWithAuth.mockResolvedValue({
      ok: false,
      status: 409,
      json: async () => ({
        error:
          "Isi pengajuan berubah sejak dibuka. Muat ulang lalu putuskan lagi.",
      }),
    });
    const { hook, fetchData, setters } = useApprovalHookWithState(
      new Map<number, unknown>([
        [STATE_REQUEST, request],
        [STATE_DECISIONS, buildInitialApprovalDecisions(request)],
      ]),
    );

    await hook.approve();

    expect(mockToastError).toHaveBeenCalledWith(
      "Isi pengajuan berubah sejak dibuka. Muat ulang lalu putuskan lagi.",
      expect.anything(),
    );
    expect(setters[STATE_REQUEST - 1]).toHaveBeenCalledWith(null);
    expect(fetchData).toHaveBeenCalledTimes(1);
  });

  it("keeps the modal open without reloading on a validation error", async () => {
    mockPatchWithAuth.mockResolvedValue({
      ok: false,
      status: 400,
      json: async () => ({
        error: "Kabel Fiber: tulis alasan item ini ditolak.",
      }),
    });
    const { hook, fetchData, setters } = useApprovalHookWithState(
      new Map<number, unknown>([
        [STATE_REQUEST, request],
        [STATE_DECISIONS, buildInitialApprovalDecisions(request)],
      ]),
    );

    await hook.approve();

    expect(mockToastError).toHaveBeenCalledWith(
      "Kabel Fiber: tulis alasan item ini ditolak.",
      expect.anything(),
    );
    expect(setters[STATE_REQUEST - 1]).not.toHaveBeenCalled();
    expect(fetchData).not.toHaveBeenCalled();
  });
});
