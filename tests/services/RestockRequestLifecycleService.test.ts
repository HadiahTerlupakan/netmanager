import { beforeEach, describe, expect, it, vi } from "vitest";

import type {
  IRestockApprovalRepository,
  RestockRequestForDecision,
} from "@/modules/inventory/domain/ports/IRestockApprovalRepository";
import {
  RestockRequestLifecycleService,
  type RestockApproveCommand,
  type RestockPurchaseOrderGenerator,
} from "@/modules/inventory/services/RestockRequestLifecycleService";

const mocks = vi.hoisted(() => ({
  logActivity: vi.fn(),
  warn: vi.fn(),
}));

vi.mock("@/lib/logger", () => ({
  logger: { logActivity: mocks.logActivity, warn: mocks.warn },
}));

vi.mock("@/modules/procurement", () => ({
  SupplierNotActiveError: class SupplierNotActiveError extends Error {},
}));

const draftRequest: RestockRequestForDecision = {
  id: "pr-1",
  nomorRequest: "PR-20261108-0001",
  status: "DRAFT",
  barangLines: [
    {
      id: "item-1",
      barangId: "barang-1",
      barangNama: "Kabel Fiber",
      jumlah: 10,
      hargaPerUnit: 5000,
    },
  ],
  jasaLines: [],
};

const approveCommand: RestockApproveCommand = {
  action: "APPROVE",
  id: "pr-1",
  tenantId: "tenant-1",
  actorId: "user-1",
  catatan: "Lanjut",
  items: [
    {
      itemId: "item-1",
      keputusan: "APPROVED",
      jumlah: 6,
      catatan: "Cukup 6 dulu",
    },
  ],
  jasaItems: [],
};

function createRepository(): {
  [K in keyof IRestockApprovalRepository]: ReturnType<typeof vi.fn>;
} {
  return {
    findRequestForDecision: vi.fn().mockResolvedValue(draftRequest),
    findBarangByIds: vi.fn().mockResolvedValue([]),
    saveApproval: vi.fn().mockResolvedValue(true),
    saveRejection: vi.fn().mockResolvedValue(true),
    findDecidedRequest: vi.fn().mockResolvedValue({
      id: "pr-1",
      nomorRequest: "PR-20261108-0001",
      status: "ORDERED",
    }),
  };
}

describe("RestockRequestLifecycleService", () => {
  let repository: ReturnType<typeof createRepository>;
  let generator: { generatePOFromPRs: ReturnType<typeof vi.fn> };
  let service: RestockRequestLifecycleService;

  beforeEach(() => {
    vi.clearAllMocks();
    repository = createRepository();
    generator = {
      generatePOFromPRs: vi
        .fn()
        .mockResolvedValue([{ id: "po-1", poNumber: "PO/2026/11/0001" }]),
    };
    service = new RestockRequestLifecycleService(
      repository as unknown as IRestockApprovalRepository,
      generator as unknown as RestockPurchaseOrderGenerator,
    );
  });

  it("menyimpan rencana per baris lalu membuat PO dan mempertahankan bentuk respons", async () => {
    const result = await service.patchRestockRequestLifecycle(approveCommand);

    expect(repository.saveApproval).toHaveBeenCalledWith(
      expect.objectContaining({
        purchaseRequestId: "pr-1",
        tenantId: "tenant-1",
        actorId: "user-1",
        catatan: "Lanjut",
        plan: {
          barangLines: [
            expect.objectContaining({
              itemId: "item-1",
              statusApproval: "APPROVED",
              catatanApproval: "Cukup 6 dulu",
              quantityChange: {
                jumlah: 6,
                jumlahDiminta: 10,
                totalHarga: 30000,
              },
            }),
          ],
          jasaLines: [],
        },
      }),
    );
    expect(generator.generatePOFromPRs).toHaveBeenCalledWith(
      ["pr-1"],
      "user-1",
    );
    expect(result).toEqual({
      success: true,
      data: {
        id: "pr-1",
        nomorRequest: "PR-20261108-0001",
        status: "ORDERED",
        _autoGeneratedPO: { id: "po-1", poNumber: "PO/2026/11/0001" },
        _poError: null,
      },
    });
    expect(mocks.logActivity).toHaveBeenCalledWith(
      expect.objectContaining({
        tenantId: "tenant-1",
        action: "APPROVE PurchaseRequest",
        details: expect.objectContaining({
          barang: [
            expect.objectContaining({
              itemId: "item-1",
              keputusan: "APPROVED",
              jumlahDiminta: 10,
              jumlahDisetujui: 6,
              catatan: "Cukup 6 dulu",
            }),
          ],
        }),
      }),
    );
  });

  it("mencari barang pengganti dengan filter tenant", async () => {
    repository.findBarangByIds.mockResolvedValue([
      { id: "barang-9", nama: "Kabel Merek B" },
    ]);

    await service.patchRestockRequestLifecycle({
      ...approveCommand,
      items: [
        {
          itemId: "item-1",
          keputusan: "APPROVED",
          jumlah: 10,
          barangIdPengganti: "barang-9",
          catatan: "Ganti merek",
        },
      ],
    });

    expect(repository.findBarangByIds).toHaveBeenCalledWith(
      ["barang-9"],
      "tenant-1",
    );
  });

  it("mengembalikan CONFLICT bila pengajuan diputuskan orang lain saat menyimpan", async () => {
    repository.saveApproval.mockResolvedValue(false);
    repository.findRequestForDecision
      .mockResolvedValueOnce(draftRequest)
      .mockResolvedValueOnce({ ...draftRequest, status: "APPROVED" });

    const result = await service.patchRestockRequestLifecycle(approveCommand);

    expect(result).toEqual({
      success: false,
      code: "CONFLICT",
      error: expect.stringContaining("sudah disetujui"),
    });
    expect(generator.generatePOFromPRs).not.toHaveBeenCalled();
  });

  it("mengembalikan CONFLICT bila baris berubah saat menyimpan", async () => {
    repository.saveApproval.mockResolvedValue(false);

    const result = await service.patchRestockRequestLifecycle(approveCommand);

    expect(result).toMatchObject({
      success: false,
      code: "CONFLICT",
      error:
        "Isi pengajuan berubah sejak dibuka. Muat ulang lalu putuskan lagi.",
    });
  });

  it("tetap menyetujui dan mengisi _poError bila PO gagal dibuat", async () => {
    generator.generatePOFromPRs.mockRejectedValue(new Error("db down"));
    repository.findDecidedRequest.mockResolvedValue({
      id: "pr-1",
      nomorRequest: "PR-20261108-0001",
      status: "APPROVED",
    });

    const result = await service.patchRestockRequestLifecycle(approveCommand);

    expect(result).toMatchObject({
      success: true,
      data: {
        status: "APPROVED",
        _autoGeneratedPO: null,
        _poError: expect.stringContaining(
          "daftar belanjanya belum bisa dibuat. Hubungi admin.",
        ),
      },
    });
    expect(mocks.warn).toHaveBeenCalled();
  });

  it("menjelaskan pemasok tidak aktif bila PO gagal karena pemasok", async () => {
    const { SupplierNotActiveError } = await import("@/modules/procurement");
    generator.generatePOFromPRs.mockRejectedValue(
      new SupplierNotActiveError("supplier-1", "INACTIVE"),
    );

    const result = await service.patchRestockRequestLifecycle(approveCommand);

    expect(result).toMatchObject({
      success: true,
      data: {
        _poError: expect.stringContaining(
          "toko untuk barang ini sedang tidak aktif. Hubungi admin.",
        ),
      },
    });
  });

  it("mengembalikan NOT_FOUND untuk pengajuan tenant lain atau yang sudah dihapus", async () => {
    repository.findRequestForDecision.mockResolvedValue(null);

    const result = await service.patchRestockRequestLifecycle(approveCommand);

    expect(result).toMatchObject({ success: false, code: "NOT_FOUND" });
  });

  it("menolak memutuskan pengajuan yang sudah tidak DRAFT", async () => {
    repository.findRequestForDecision.mockResolvedValue({
      ...draftRequest,
      status: "REJECTED",
    });

    const result = await service.patchRestockRequestLifecycle(approveCommand);

    expect(result).toMatchObject({ success: false, code: "CONFLICT" });
    expect(repository.saveApproval).not.toHaveBeenCalled();
  });

  it("meneruskan galat aturan baris dari resolver tanpa menyimpan", async () => {
    const result = await service.patchRestockRequestLifecycle({
      ...approveCommand,
      items: [{ itemId: "item-1", keputusan: "REJECTED", catatan: "Batal" }],
    });

    expect(result).toMatchObject({ success: false, code: "CONFLICT" });
    expect(repository.saveApproval).not.toHaveBeenCalled();
  });

  it("menolak seluruh pengajuan dengan alasan", async () => {
    repository.findDecidedRequest.mockResolvedValue({
      id: "pr-1",
      nomorRequest: "PR-20261108-0001",
      status: "REJECTED",
    });

    const result = await service.patchRestockRequestLifecycle({
      action: "REJECT",
      id: "pr-1",
      tenantId: "tenant-1",
      actorId: "user-1",
      catatan: "Anggaran habis",
    });

    expect(repository.saveRejection).toHaveBeenCalledWith(
      expect.objectContaining({
        purchaseRequestId: "pr-1",
        tenantId: "tenant-1",
        catatan: "Anggaran habis",
      }),
    );
    expect(result).toMatchObject({
      success: true,
      data: { status: "REJECTED" },
    });
    expect(generator.generatePOFromPRs).not.toHaveBeenCalled();
  });

  it("mengembalikan CONFLICT bila penolakan kalah balapan", async () => {
    repository.saveRejection.mockResolvedValue(false);
    repository.findRequestForDecision
      .mockResolvedValueOnce(draftRequest)
      .mockResolvedValueOnce({ ...draftRequest, status: "APPROVED" });

    const result = await service.patchRestockRequestLifecycle({
      action: "REJECT",
      id: "pr-1",
      tenantId: "tenant-1",
      actorId: "user-1",
      catatan: "Anggaran habis",
    });

    expect(result).toMatchObject({ success: false, code: "CONFLICT" });
  });
});
