-- Penjaga konkurensi penerbitan material peta rencana OSP.
--
-- Tanpa kunci ini, dua POST /api/planning/[id]/peta/material yang
-- tumpang-tindih (satu perencana mengeklik dua kali, dua tab, atau POST
-- menggantung lalu halaman di-reload) sama-sama tidak menemukan baris lalu
-- sama-sama membuatnya: baris item otomatis ganda yang menetap dan membuat
-- estimasi budget terhitung dobel.
--
-- Item manual ber-"sourceKey" NULL tidak pernah bentrok: Postgres
-- memperlakukan NULL sebagai distinct, sehingga berapa pun jumlah item yang
-- diketik manusia tetap sah di bawah kunci ini. Baris isAutoGenerated = true
-- ber-"sourceKey" NULL juga tidak menghalangi pembuatan index, dengan alasan
-- yang sama.

-- Membersihkan duplikat yang mungkin sudah lahir dari balapan di atas,
-- menyisakan baris terbaru per (planningId, sourceKey). Hanya menyentuh item
-- otomatis ber-"sourceKey" terisi — duplikat seperti itu per definisi adalah
-- salinan tak diinginkan dari item yang sama, dan nilainya ditulis ulang dari
-- peta pada penerbitan berikutnya. Item manual tidak tersentuh.
DELETE FROM "PlanningItem" AS duplikat
USING "PlanningItem" AS termuda
WHERE duplikat."sourceKey" IS NOT NULL
  AND duplikat."isAutoGenerated" = true
  AND termuda."sourceKey" IS NOT NULL
  AND termuda."isAutoGenerated" = true
  AND duplikat."planningId" = termuda."planningId"
  AND duplikat."sourceKey" = termuda."sourceKey"
  AND (duplikat."createdAt", duplikat."id") < (termuda."createdAt", termuda."id");

-- CreateIndex
CREATE UNIQUE INDEX "PlanningItem_planningId_sourceKey_key" ON "PlanningItem"("planningId", "sourceKey");
